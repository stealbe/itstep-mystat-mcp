"""Command line interface: setup, run, status, sync, login.

Installed with ``uv tool install itstep-mystat-mcp`` the user gets a single
command::

    itstep-mystat-mcp setup     # asks for login/password, writes config,
                                # registers the server in local LLM clients
    itstep-mystat-mcp run       # MCP server over stdio (what clients call)
    itstep-mystat-mcp status    # paths, credentials, cache, token
    itstep-mystat-mcp sync      # one-off sync from the terminal
"""

from __future__ import annotations

import argparse
import asyncio
import getpass
import json
import os
import shutil
import sys
from pathlib import Path

from . import __version__
from .clients import AVAILABLE, Change, detect_clients, manual_snippet, register, verify_registrations, _run_cli, SERVER_NAME
from .config import Settings, app_config_dir, ConfigError

DEFAULT_ENV = app_config_dir() / ".env"


# ------------------------------------------------------------------- utils ---
def _ensure_utf8_streams() -> None:
    """Force UTF-8 on the console streams.

    Windows picks the codec itself: an attached console uses the console code
    page (866 on a Russian system) and a redirected stream uses the ANSI code
    page (1251). Neither is stable across machines, and cp866 has no Ukrainian
    letters (і, ї, є, ґ) at all, so a log line or a JSON summary could raise
    ``UnicodeEncodeError``. Pinning UTF-8 makes the bytes deterministic, and
    ``errors="replace"`` keeps the command alive on a terminal that cannot
    render a glyph.
    """
    for stream in (sys.stdout, sys.stderr):
        reconfigure = getattr(stream, "reconfigure", None)
        if reconfigure is None:
            continue
        try:
            reconfigure(encoding="utf-8", errors="replace")
        except (ValueError, OSError):  # detached or non-reconfigurable stream
            pass


def _read_env(path: Path) -> dict[str, str]:
    from dotenv import dotenv_values

    if not path.is_file():
        return {}
    values = dotenv_values(path, encoding="utf-8", interpolate=False)
    return {k: v for k, v in values.items() if v is not None}


def _encode_env_value(value: str) -> str:
    """Encode a value so python-dotenv reads it back character for character.

    A bare ``KEY=value`` is written whenever it survives parsing, because that
    is what people expect to see for logins and Windows paths. Bare values are
    unsafe when they contain whitespace (leading/trailing spaces are trimmed,
    ``" #"`` starts an inline comment) or quotes, so those are double-quoted
    with backslashes escaped.

    Whatever is produced is verified after the file is written; this function
    only chooses the readable form.
    """
    if (
        value == value.strip()
        and value
        and not any(ch in value for ch in (" ", "\t", "#", '"', "'"))
        and not value.startswith("=")
    ):
        return value
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def _write_env(path: Path, values: dict[str, str]) -> None:
    from dotenv import dotenv_values

    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# ITStep MyStat MCP configuration",
        "# Generated by `itstep-mystat-mcp setup`. Keep this file private.",
        "# Values are written bare when safe, otherwise double-quoted;",
        "# edit them the same way or re-run the setup command.",
        "",
    ]
    for key, value in values.items():
        lines.append(f"{key}={_encode_env_value(value)}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    try:
        if os.name == "posix":
            os.chmod(path, 0o600)
    except OSError:
        pass

    # Verify the round-trip: a silently mangled password costs a confusing 401.
    written = dotenv_values(path, encoding="utf-8", interpolate=False)
    broken = [key for key, value in values.items() if written.get(key) != value]
    if broken:
        raise ConfigError(
            "could not write these settings faithfully: "
            + ", ".join(broken)
            + f"; the file {path} may be malformed (values are never printed)"
        )


def _prompt(text: str, default: str = "") -> str:
    suffix = f" [{default}]" if default else ""
    try:
        answer = input(f"{text}{suffix}: ").strip()
    except EOFError:
        answer = ""
    return answer or default


def _prompt_secret(text: str) -> str:
    """Read a secret, keeping its content exactly as entered.

    Only the line ending is removed: a trailing ``\\r`` sneaks in when the
    paste buffer comes from Windows apps, and an embedded line break would
    split the .env file into two lines.
    """
    raw = sys.stdin.readline() if not sys.stdin.isatty() else getpass.getpass(text)
    return raw.rstrip("\r\n")


# -------------------------------------------------------------------- setup ---
def cmd_setup(args: argparse.Namespace) -> int:
    env_path = Path(args.env_file).expanduser() if args.env_file else DEFAULT_ENV
    existing = _read_env(env_path)

    login = args.login or existing.get("MYSTAT_LOGIN") or existing.get("LOGIN") or ""
    password = os.environ.get("MYSTAT_PASSWORD") or existing.get("MYSTAT_PASSWORD") or existing.get("PASSWORD") or ""

    if not args.yes:
        login = _prompt("MyStat login", login) if not login else login
        if not password:
            first = _prompt_secret("MyStat password (input hidden): ")
            second = _prompt_secret("Repeat password: ")
            if first != second:
                print("Passwords do not match; nothing written.", file=sys.stderr)
                return 2
            password = first

    if not login or not password:
        print("Login and password are required.", file=sys.stderr)
        return 2

    for name, value in (("login", login), ("password", password)):
        if "\r" in value or "\n" in value:
            print(
                f"The {name} contains a line break; it would corrupt the .env file. "
                "Nothing written — paste the value again.",
                file=sys.stderr,
            )
            return 2
        if value != value.strip():
            print(
                f"note: the {name} has leading/trailing spaces and they are kept as is. "
                "If the paste added them, run setup again.",
                file=sys.stderr,
            )

    # Absolute on purpose: an MCP client starts the server from an arbitrary
    # working directory, so a relative path in .env would resolve elsewhere.
    cache_dir = (
        Path(args.cache_dir).expanduser().resolve()
        if args.cache_dir
        else (app_config_dir() / "cache").resolve()
    )
    cache_dir.mkdir(parents=True, exist_ok=True)

    values = {
        "MYSTAT_LOGIN": login,
        "MYSTAT_PASSWORD": password,
        "MYSTAT_BASE_URL": existing.get("MYSTAT_BASE_URL", "https://mapi.itstep.org/v1/mystat"),
        "MYSTAT_LANGUAGE": existing.get("MYSTAT_LANGUAGE", "uk"),
        "MYSTAT_STATUS_FILTER": existing.get("MYSTAT_STATUS_FILTER", "3"),
        "CACHE_DIR": str(cache_dir),
        "DATABASE_PATH": str(cache_dir / "mystat.db"),
        "SYNC_LIMIT": existing.get("SYNC_LIMIT", "1000"),
        "HTTP_TIMEOUT": existing.get("HTTP_TIMEOUT", "30"),
        "MAX_ATTACHMENT_SIZE_MB": existing.get("MAX_ATTACHMENT_SIZE_MB", "100"),
    }
    try:
        _write_env(env_path, values)
    except ConfigError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 3
    print(f"Credentials written to {env_path}")
    print(
        f"stored login: {len(login)} chars, password: {len(password)} chars — "
        "compare with what you typed or pasted (the values themselves are never shown)"
    )

    local_env = Path(__file__).resolve().parents[1] / ".env"
    if local_env.is_file() and local_env.resolve() != env_path.resolve():
        print(
            f"note: {local_env} exists and takes priority over {env_path} "
            "(project-local .env wins).",
            file=sys.stderr,
        )

    if args.verify:
        ok, message = _verify(env_path)
        print(("login verified: " if ok else "login NOT verified: ") + message)
        if not ok:
            return 3

    clients = _select_clients(args.client)
    if not clients:
        print("No clients selected; skipping MCP registration.")
        return 0

    # --reinstall: remove existing entries first (where supported)
    if args.reinstall:
        for name in clients:
            if name == "opencode":
                _run_cli(["opencode", "mcp", "remove", SERVER_NAME], timeout=30)
            elif name == "claude-code":
                _run_cli([shutil.which("claude"), "mcp", "remove", SERVER_NAME], timeout=30)
            elif name == "codex":
                _run_cli(["codex", "mcp", "remove", SERVER_NAME], timeout=30)
            # claude-desktop has no CLI remove; file fallback handles it.

    # Determine which clients to actually register, based on --registration
    strategy = args.registration  # "auto" | "cli" | "file"

    print("\nRegistering MCP server (strategy: {})".format(strategy))

    # Phase 1: perform the registration(s)
    raw_changes = register(clients)

    # Phase 2: verify via mcp list (for CLI-registered servers)
    if strategy in ("auto", "cli"):
        verified_changes = verify_registrations(clients)
    else:
        # file‑only strategy: mark as unverified (they were written directly)
        verified_changes = []
        for c in raw_changes:
            verified_changes.append(Change(
                client=c.client, path=c.path, ok=c.ok,
                method="file", verified=False, detail=c.detail))

    # Phase 3: print results
    failures = 0
    for change in verified_changes:
        print("  " + change.line())
        failures += 0 if change.ok else 1

    if failures and strategy == "cli":
        print("\nCould not register everywhere via CLI. Add this snippet manually:\n")
        print(manual_snippet())

    print("\nDone. Restart the client (or reload its window) to pick up the server.")
    return 0


def _select_clients(requested: list[str] | None) -> list[str]:
    if not requested or requested == ["auto"]:
        found = detect_clients()
        return found or ["opencode"]
    if requested == ["none"]:
        return []
    if requested == ["all"]:
        return list(AVAILABLE)
    return [name for name in requested if name in AVAILABLE]


def _verify(env_path: Path) -> tuple[bool, str]:
    import httpx

    settings = Settings.from_env(env_path)
    try:
        response = httpx.post(
            f"{settings.base_url}/auth/login",
            json={"login": settings.login, "password": settings.password},
            headers={"Content-Type": "application/json", "X-Language": settings.language},
            timeout=settings.http_timeout,
        )
    except httpx.HTTPError as exc:
        return False, f"network error: {type(exc).__name__}: {exc}"
    if response.status_code == 200 and len(response.text.strip()) > 20:
        return True, "token received"
    if response.status_code == 401:
        return False, "credentials rejected (401 error_unauthorized)"
    return False, f"HTTP {response.status_code}: {response.text.strip()[:120]}"


# -------------------------------------------------------------------- other ---
def cmd_run(args: argparse.Namespace) -> int:
    from .server import main as server_main

    server_main()
    return 0


def cmd_status(args: argparse.Namespace) -> int:
    from .cache import Cache

    settings = Settings.from_env()
    print(f"version:      {__version__}")
    print(f"env file:     {settings.env_file or '(not found)'}")
    print(f"cache dir:    {settings.cache_dir}")
    print(f"database:     {settings.database_path}")
    print(f"credentials:  {'configured' if settings.has_credentials else 'MISSING'}")
    print(f"base url:     {settings.base_url}")

    async def inspect() -> None:
        if not settings.database_path.exists():
            print("database:     not created yet (run a sync)")
            return
        cache = await Cache(settings.database_path).open()
        try:
            counts = await cache.count_homeworks()
            auth = await cache.get_auth()
            last_sync = await cache.get_state("last_sync")
            print(f"homework:     {counts['total']} (missing: {counts['missing']})")
            print(f"token:        {'stored' if auth else 'none'}"
                  f"{' exp=' + str(auth['expires_at']) if auth else ''}")
            print(f"last sync:    {json.dumps(last_sync) if last_sync else 'never'}")
            print(f"fts5:         {cache.fts_enabled}")
        finally:
            await cache.close()

    asyncio.run(inspect())
    return 0


async def _with_service():
    import httpx

    from .api import MyStatAPI
    from .auth import AuthManager
    from .cache import Cache
    from .homework import HomeworkService

    settings = Settings.from_env()
    settings.ensure_directories()
    cache = await Cache(settings.database_path).open()
    client = httpx.AsyncClient(base_url=settings.base_url,
                               timeout=httpx.Timeout(settings.http_timeout),
                               follow_redirects=True)
    auth = AuthManager(settings, cache, client)
    api = MyStatAPI(settings, auth, client)
    return settings, cache, client, auth, HomeworkService(settings, cache, api)


def cmd_sync(args: argparse.Namespace) -> int:
    async def run() -> dict:
        settings, cache, client, _auth, service = await _with_service()
        try:
            return await service.sync(force=args.force,
                                      download_attachments=not args.no_attachments)
        finally:
            await client.aclose()
            await cache.close()

    summary = asyncio.run(run())
    print(json.dumps(summary, ensure_ascii=False, indent=2))
    return 0 if summary["error_count"] == 0 else 1


def cmd_login(args: argparse.Namespace) -> int:
    async def run() -> dict:
        _settings, cache, client, auth, _service = await _with_service()
        try:
            await auth.login()
            return await auth.status()
        finally:
            await client.aclose()
            await cache.close()

    print(json.dumps(asyncio.run(run()), ensure_ascii=False, indent=2))
    return 0


def cmd_logout(args: argparse.Namespace) -> int:
    async def run() -> None:
        _settings, cache, client, auth, _service = await _with_service()
        try:
            await auth.logout()
        finally:
            await client.aclose()
            await cache.close()

    asyncio.run(run())
    print("token removed")
    return 0


# --------------------------------------------------------------------- main ---
def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="itstep-mystat-mcp",
        description="ITStep MyStat homework MCP server",
    )
    parser.add_argument("--version", action="version", version=f"%(prog)s {__version__}")
    sub = parser.add_subparsers(dest="command")

    setup = sub.add_parser("setup", help="write credentials and register the server in LLM clients")
    setup.add_argument("--login", help="MyStat login (otherwise asked interactively)")
    setup.add_argument("--env-file", help=f"where to write credentials (default: {DEFAULT_ENV})")
    setup.add_argument("--cache-dir", help="cache directory (default: next to the config)")
    setup.add_argument("--client", action="append", choices=[*AVAILABLE, "auto", "all", "none"],
                       help="target client; repeatable (default: auto-detect)")
    setup.add_argument("--registration", choices=["auto", "cli", "file"],
                       default="auto",
                       help="registration strategy: auto try CLI first, cli abort on failure, file only (default: auto)")
    setup.add_argument("--reinstall", action="store_true",
                       help="remove any existing server entry before re‑adding via CLI")
    setup.add_argument("--verify", dest="verify", action="store_true", default=True,
                       help="verify the credentials with a real login (default)")
    setup.add_argument("--no-verify", dest="verify", action="store_false")
    setup.add_argument("-y", "--yes", action="store_true",
                       help="do not prompt; take values from flags, .env or the environment")
    setup.set_defaults(func=cmd_setup)

    run = sub.add_parser("run", help="run the MCP server over stdio")
    run.set_defaults(func=cmd_run)

    status = sub.add_parser("status", help="show configuration and cache state")
    status.set_defaults(func=cmd_status)

    sync = sub.add_parser("sync", help="sync homework from the terminal")
    sync.add_argument("--force", action="store_true")
    sync.add_argument("--no-attachments", action="store_true")
    sync.set_defaults(func=cmd_sync)

    login = sub.add_parser("login", help="force a login and store the token")
    login.set_defaults(func=cmd_login)

    logout = sub.add_parser("logout", help="remove the stored token")
    logout.set_defaults(func=cmd_logout)

    return parser


def main(argv: list[str] | None = None) -> int:
    _ensure_utf8_streams()
    parser = build_parser()
    args = parser.parse_args(argv)
    if not getattr(args, "command", None):
        return cmd_run(args)
    return args.func(args)
